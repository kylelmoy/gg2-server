using GG2.Bots;
using GG2.Maps;

namespace GG2.Tests;

/// <summary>
/// <c>nav/manifest.tsv</c> names the walkmask every checked-in graph was built
/// against, and this is what stops it going stale.
/// </summary>
/// <remarks>
/// <b>The gate this repository did not have.</b> A nav graph is keyed on the
/// map's NAME (<c>NavCache.Key</c>, deliberately — its remarks say why the MD5
/// cannot be the key), so a graph built against an older version of a map loads
/// perfectly and hands bots terrain that is not there. The mask width and height
/// in the header catch a resize and nothing else. Nothing anywhere went red, and
/// the symptom is bots walking into walls, which reads as a bot bug.
/// <para>
/// <b>This is a two-sided check and both sides matter.</b> A map edited
/// without regenerating nav fails here; so does a nav graph regenerated against
/// something other than the maps in this repository. CLAUDE.md's rule about
/// pinned numbers applies — a red here is "re-record and say so in the commit"
/// when you meant to change the geometry, and an alarm when you did not.
/// </para>
/// <para>
/// To re-record, having checked the change is one you meant:
/// <code>
/// GG2_UPDATE_NAV_MANIFEST=1 dotnet test GG2.sln --filter NavManifestTests
/// </code>
/// which rewrites the file from the maps on disk and then passes. <b>The
/// update path is deliberately not silent about being used</b> — it fails the
/// run it rewrote on, so a manifest cannot be regenerated by a CI job that
/// happened to have the variable set and be reported as green.
/// </para>
/// </remarks>
public sealed class NavManifestTests
{
    private const string UpdateVariable = "GG2_UPDATE_NAV_MANIFEST";

    /// <summary>
    /// Every graph in <c>nav/</c> is recorded against the map it was built from.
    /// </summary>
    [Fact]
    public void EveryGraphMatchesItsMap()
    {
        ReferenceTree.RequireNavCache();

        var directory = ReferenceTree.NavCacheDirectory;
        var graphs = NavCache.List(directory);

        Assert.NotEmpty(graphs);

        var actual = new List<(string Key, string Hash)>();
        var missingMaps = new List<string>();

        foreach (var (map, area) in graphs)
        {
            // A graph whose map is not here cannot be checked. Collected rather
            // than thrown on, so the message names all of them at once — for the
            // checked-in set this can only mean a map went missing.
            if (!File.Exists(ReferenceTree.MapPath(map)))
            {
                missingMaps.Add(map);
                continue;
            }

            var area_ = LevelMap.FromPng(map, ReferenceTree.ReadMap(map)).ForArea(area);
            actual.Add((NavCache.Key(map, area), NavManifest.HashOf(area_)));
        }

        Assert.True(
            missingMaps.Count == 0,
            $"nav graphs with no map to check them against: {string.Join(", ", missingMaps)}");

        if (Environment.GetEnvironmentVariable(UpdateVariable) == "1")
        {
            NavManifest.Write(Path.Combine(directory, NavManifest.FileName), actual);

            Assert.Fail(
                $"""
                 Rewrote {NavManifest.FileName} from the maps on disk — {actual.Count} graphs.

                 This is a FAILURE on purpose: re-run without {UpdateVariable} to see it pass,
                 check the diff is the change you meant, and say so in the commit message.
                 """);
        }

        var manifest = NavManifest.Load(directory);
        var wrong = new List<string>();

        foreach (var (key, hash) in actual)
        {
            switch (manifest.Check(key, hash))
            {
                case NavMatch.Match:
                    break;

                case NavMatch.Unknown:
                    wrong.Add($"{key}: not in the manifest (should be {hash})");
                    break;

                case NavMatch.Mismatch:
                    wrong.Add($"{key}: manifest has {manifest.HashFor(key)}, the map hashes to {hash}");
                    break;
            }
        }

        Assert.True(
            wrong.Count == 0,
            $"""
             {wrong.Count} of {actual.Count} nav graphs disagree with the maps they were built from:

             {string.Join("\n             ", wrong)}

             Either a map changed and its graph was not regenerated (bots will path against
             geometry that is not there), or the graphs were regenerated against different
             maps. Regenerate with gg2-nav-gen, then:
                 {UpdateVariable}=1 dotnet test GG2.sln --filter NavManifestTests
             """);
    }

    /// <summary>
    /// The control arm: the check must be able to FAIL.
    /// </summary>
    /// <remarks>
    /// <b>Without this the test above is satisfiable by a manifest that
    /// matches everything.</b> That is CLAUDE.md's recurring shape — the code
    /// self-consistent, the claim about coverage false — and here it would be
    /// invisible, because the only observable difference is whether a stale
    /// graph gets refused months from now. So: mutate one cell of a real
    /// walkmask and assert the manifest notices.
    /// </remarks>
    [Fact]
    public void AChangedWalkmaskIsDetected()
    {
        ReferenceTree.RequireNavCache();

        var map = LevelMap.FromPng("ctf_truefort", ReferenceTree.ReadMap("ctf_truefort")).ForArea(1);
        var real = NavManifest.HashOf(map);

        var manifest = NavManifest.Load(ReferenceTree.NavCacheDirectory);

        Assert.Equal(NavMatch.Match, manifest.Check("ctf_truefort_a1", real));

        // One flipped cell out of 891x180 — the smallest possible geometry edit,
        // and the one a dimension check cannot see.
        var cells = map.Walkmask.ToCellBytes();
        var index = Array.FindIndex(cells, c => c == 0);
        Assert.True(index >= 0, "ctf_truefort has no open cell, which cannot be");
        cells[index] = 1;

        var mutated = NavManifest.HashOf(cells, map.Walkmask.Width, map.Walkmask.Height, map.Entities);

        Assert.NotEqual(real, mutated);
        Assert.Equal(NavMatch.Mismatch, manifest.Check("ctf_truefort_a1", mutated));
    }

    /// <summary>
    /// The second control arm: an ENTITY-only change is detected too.
    /// </summary>
    /// <remarks>
    /// <b>This is the one the first version of the check would have failed.</b>
    /// It hashed the walkmask alone, and <c>cp_dirtbowl</c>'s three areas — which
    /// carry different graphs, of 835, 837 and 837 nodes — hashed identically,
    /// because <c>LevelMap.ForArea</c> slices entities and shares the mask. A
    /// door or a gate could move and nothing would notice. Asserting the three
    /// areas differ is the cheapest statement of "entities are in the hash" that
    /// uses only real shipped data.
    /// </remarks>
    [Fact]
    public void EntitiesAreInTheHash()
    {
        var png = ReferenceTree.ReadMap("cp_dirtbowl");
        var map = LevelMap.FromPng("cp_dirtbowl", png);

        var one = NavManifest.HashOf(map.ForArea(1));
        var two = NavManifest.HashOf(map.ForArea(2));
        var three = NavManifest.HashOf(map.ForArea(3));

        // The premise: the mask really is shared, so nothing but the entities
        // can be telling these apart.
        Assert.Equal(
            Convert.ToHexStringLower(map.ForArea(1).Walkmask.ToCellBytes().AsSpan(0, 32)),
            Convert.ToHexStringLower(map.ForArea(3).Walkmask.ToCellBytes().AsSpan(0, 32)));
        Assert.Equal(map.ForArea(1).Walkmask.SolidCount(), map.ForArea(3).Walkmask.SolidCount());

        Assert.NotEqual(one, two);
        Assert.NotEqual(two, three);
        Assert.NotEqual(one, three);
    }

    /// <summary>
    /// A graph nobody recorded is <see cref="NavMatch.Unknown"/>, not a failure.
    /// </summary>
    /// <remarks>
    /// <b>The operator with their own maps is the reason.</b> They generate
    /// graphs this repository has never seen and must not be worse off for the
    /// manifest existing — <c>NavCache.TryLoad</c>'s "a miss is not an error"
    /// contract reaches this too. A version of this check that refused unknown
    /// graphs would break every custom-map server on upgrade.
    /// </remarks>
    [Fact]
    public void AnUnrecordedGraphIsNotRefused()
    {
        var manifest = NavManifest.Load(ReferenceTree.NavCacheDirectory);

        Assert.Equal(NavMatch.Unknown, manifest.Check("someones_own_map_a1", new string('0', 32)));
    }

    /// <summary>A directory with no manifest checks nothing and throws nothing.</summary>
    [Fact]
    public void ADirectoryWithNoManifestIsEmpty()
    {
        var empty = NavManifest.Load(Path.GetTempPath());

        Assert.Equal(0, empty.Count);
        Assert.Equal(NavMatch.Unknown, empty.Check("ctf_truefort_a1", new string('0', 32)));
    }
}
