using GG2.Bots;

namespace GG2.Tests;

/// <summary>
/// Locates the reference checkout — the Game Maker 8 implementation that is also
/// the client, and therefore the specification.
/// </summary>
/// <remarks>
/// The map tests read the maps out of it rather than copying them here. That is
/// deliberate: a copied map is a map that can silently go stale, and phase 0's
/// exit criterion is about the maps the stock client actually ships.
/// <para>
/// Set <c>GG2_REFERENCE</c> to use an existing checkout. Without it, the first
/// test that asks clones <see cref="Upstream"/> at <see cref="PinnedCommit"/>
/// into a per-user cache (<see cref="CacheRoot"/>) and every later run reuses
/// it, so a fresh clone of this repo needs git and a network connection once
/// and nothing on disk. The tree is <b>read-only</b> from this repo (CLAUDE.md).
/// </para>
/// <para>
/// <b>The reference is stock upstream GG2</b>, pinned to the commit the suite
/// was written against: <c>V2.9.2-78-gea8d6951</c>, upstream's master, not the
/// <c>V2.9.2</c> tag. Stock GG2 is the thing a stock client runs, and that is
/// the only thing this port owes compatibility to. <c>.github/workflows/release.yml</c>
/// checks out the same commit and must move with <see cref="PinnedCommit"/>.
/// </para>
/// </remarks>
public static class ReferenceTree
{
    public const string EnvironmentVariable = "GG2_REFERENCE";

    /// <summary>
    /// Map names (without extension) that this repository authors itself —
    /// generated by a checked-in script, present in <c>maps/</c>, and absent
    /// from the reference by design.
    /// </summary>
    /// <remarks>
    /// Every census that makes a claim about what the SHIPPED maps contain
    /// must exclude these, or adding a port-authored map silently changes what
    /// "no shipped map does X" means. <see cref="MapCopyTests"/> asserts the
    /// other direction: none of these may exist in the reference tree.
    /// <c>gg_debug2</c> is <c>tools/gen-gg-debug2.js</c>'s output.
    /// </remarks>
    public static readonly IReadOnlySet<string> PortAuthoredMaps =
        new HashSet<string>(StringComparer.Ordinal) { "gg_debug2" };

    public const string NavCacheEnvironmentVariable = "GG2_NAVCACHE";

    public const string Upstream = "https://github.com/Gang-Garrison-2/Gang-Garrison-2.git";

    public const string PinnedCommit = "ea8d69511ee1a2f76bc8266bf890764f480c4993";

    /// <summary>
    /// Where a cloned reference is kept: one directory per pinned commit (its
    /// first twelve hex digits) under
    /// the user's local application data, shared by every worktree of this repo.
    /// </summary>
    public static string CacheRoot =>
        Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
            "gg2-server", "reference");

    private static readonly Lazy<string> Cached = new(EnsureCached, LazyThreadSafetyMode.ExecutionAndPublication);

    /// <summary>
    /// Root of the checkout: <c>GG2_REFERENCE</c> as given, whether or not it
    /// exists, or the cached clone, made on first use.
    /// </summary>
    public static string Root =>
        Environment.GetEnvironmentVariable(EnvironmentVariable) is { Length: > 0 } fromEnv
            ? fromEnv
            : Cached.Value;

    /// <summary>
    /// Clones <see cref="Upstream"/> at <see cref="PinnedCommit"/> into the cache
    /// unless it is already there.
    /// </summary>
    /// <remarks>
    /// Only <c>Source/gg2</c> is checked out, from a depth-1 fetch of the one
    /// commit, so the cost is that subtree (~17 MB) rather than the history.
    /// The clone is built beside its final name and renamed into place, so a
    /// run that dies halfway leaves no directory that looks complete, and two
    /// test processes racing (two lanes' worktrees) both end up reading the
    /// one that won.
    /// </remarks>
    private static string EnsureCached()
    {
        // Short names on purpose: GG2's deepest sprite path is already close to
        // Windows' 260-character limit before the cache's own prefix is added.
        var final = Path.Combine(CacheRoot, PinnedCommit[..12]);

        if (File.Exists(Path.Combine(final, "Source", "gg2", "Constants.xml")))
            return final;

        Directory.CreateDirectory(CacheRoot);
        var staging = Path.Combine(CacheRoot, $"{PinnedCommit[..12]}.{Guid.NewGuid():N}"[..21]);

        try
        {
            Git(CacheRoot, "init", "--quiet", staging);
            Git(staging, "config", "core.longpaths", "true");
            Git(staging, "remote", "add", "origin", Upstream);
            Git(staging, "sparse-checkout", "set", "Source/gg2");
            Git(staging, "fetch", "--quiet", "--depth", "1", "origin", PinnedCommit);
            Git(staging, "checkout", "--quiet", "--detach", "FETCH_HEAD");

            try
            {
                Directory.Move(staging, final);
            }
            catch (IOException) when (Directory.Exists(final))
            {
                // Another process got there first; its copy is the same commit.
            }
        }
        finally
        {
            if (Directory.Exists(staging))
                DeleteTree(staging);
        }

        return final;
    }

    private static void Git(string workingDirectory, params string[] arguments)
    {
        var start = new System.Diagnostics.ProcessStartInfo("git")
        {
            WorkingDirectory = workingDirectory,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
        };

        foreach (var argument in arguments)
            start.ArgumentList.Add(argument);

        using var git = System.Diagnostics.Process.Start(start)
            ?? throw new InvalidOperationException("could not start git");

        var stderr = git.StandardError.ReadToEndAsync();
        git.StandardOutput.ReadToEnd();
        git.WaitForExit();

        if (git.ExitCode != 0)
            throw new InvalidOperationException(
                $"""
                 git {string.Join(' ', arguments)} failed ({git.ExitCode}) while caching the
                 GG2 reference at {CacheRoot}:

                 {stderr.Result.Trim()}

                 Set {EnvironmentVariable} to an existing checkout of {Upstream}
                 at {PinnedCommit} to skip the clone.
                 """);
    }

    /// <summary>Deletes a directory git wrote, whose object files are read-only on Windows.</summary>
    private static void DeleteTree(string path)
    {
        foreach (var file in Directory.EnumerateFiles(path, "*", SearchOption.AllDirectories))
            File.SetAttributes(file, FileAttributes.Normal);

        Directory.Delete(path, recursive: true);
    }

    /// <summary>
    /// The reference's own copy of the built-in map PNGs. Only
    /// <see cref="MapCopyTests"/> should read it; every other test reads
    /// <see cref="MapsDirectory"/>, which needs no checkout.
    /// </summary>
    public static string IncludedFiles => Path.Combine(Root, "Source", "gg2", "Included Files");

    /// <summary>
    /// Where the bot nav caches live: <c>GG2_NAVCACHE</c>, or <c>nav/</c> at the
    /// root of this repo.
    /// </summary>
    /// <remarks>
    /// <b>Deliberately NOT under <see cref="Root"/>.</b> A nav graph is
    /// <em>this project's</em> artefact and the reference knows nothing about
    /// it, so it does not belong in a tree CLAUDE.md calls read-only.
    /// <para>
    /// <b>Checked in</b>, so a fresh clone has them and can run a bot.
    /// <see cref="RequireNavCache"/> still guards, because a clone can still
    /// delete them.
    /// <para>
    /// <b>Stored gzipped</b> — 1.11 MB rather than 35.68 MB on disk.
    /// <see cref="NavCache.List"/> accepts both containers, which is why this
    /// probe goes through it rather than globbing.
    /// </para>
    /// </para>
    /// </remarks>
    public static string NavCacheDirectory =>
        Environment.GetEnvironmentVariable(NavCacheEnvironmentVariable) is { Length: > 0 } fromEnv
            ? fromEnv
            : Path.Combine(RepositoryRoot, "nav");

    public static bool IsAvailable => Directory.Exists(IncludedFiles);

    public static bool HasNavCache =>
        Directory.Exists(NavCacheDirectory) && NavCache.List(NavCacheDirectory).Count > 0;

    public static void RequireNavCache() =>
        Assert.True(
            HasNavCache,
            $"""
             No bot nav caches at {NavCacheDirectory}.

             These are checked in, so a clone should have them — a missing nav/ means
             they were deleted, or {NavCacheEnvironmentVariable} points somewhere else.
             Otherwise rebuild them:

                 dotnet run --project src/GG2.Host -- navgen
             """);

    /// <summary>
    /// This repo's root, found by walking up from the test binary until
    /// <c>GG2.sln</c> turns up.
    /// </summary>
    /// <remarks>
    /// The alternative — copying the caches into the build output the way
    /// <c>Fixtures/</c> is copied — would put 34 MB through every build, twice
    /// over for Debug and Release.
    /// </remarks>
    public static string RepositoryRoot
    {
        get
        {
            for (var directory = new DirectoryInfo(AppContext.BaseDirectory);
                 directory is not null;
                 directory = directory.Parent)
            {
                if (File.Exists(Path.Combine(directory.FullName, "GG2.sln")))
                    return directory.FullName;
            }

            // Only reachable if the tests are run from outside the tree; the
            // env var is then the way in, and RequireNavCache says so.
            return AppContext.BaseDirectory;
        }
    }

    /// <summary>
    /// Where the built-in map PNGs are read from: <c>maps/</c> at the root of
    /// this repo, or the reference's <c>Included Files</c> if that is missing.
    /// </summary>
    /// <remarks>
    /// <b>The maps are checked in</b>, which is in tension with <em>a copied map
    /// is a map that can silently go stale</em> — copying them does not answer
    /// that by itself. <see cref="MapCopyTests"/> is the answer: whenever a
    /// reference checkout is present, every copied map is asserted
    /// byte-identical to the reference's. So the copy is gated rather than
    /// trusted, and the tests stop needing a checkout to run at all.
    /// <para>
    /// <b>Falling back to the reference matters for more than tidiness.</b>
    /// <c>LevelEntityTests</c> compares every entity against
    /// <c>Fixtures/maps.json</c>; pointing it at a copy that is never checked
    /// against the reference would leave both sides reading the same bytes and
    /// gate nothing about drift, which is the coverage that check preserves.
    /// </para>
    /// </remarks>
    public static string MapsDirectory
    {
        get
        {
            var copied = Path.Combine(RepositoryRoot, "maps");
            return File.Exists(Path.Combine(copied, "ctf_truefort.png")) ? copied : IncludedFiles;
        }
    }

    /// <summary>
    /// The names of the maps a stock client ships: every PNG in
    /// <see cref="MapsDirectory"/> except <see cref="PortAuthoredMaps"/>, sorted.
    /// </summary>
    /// <remarks>
    /// Read from <c>maps/</c>, not the reference, so a census over the shipped
    /// maps needs no checkout. <see cref="MapCopyTests"/> is what makes that the
    /// same list: it holds <c>maps/</c> byte-identical to the reference.
    /// </remarks>
    public static string[] ShippedMapNames() =>
        Directory.GetFiles(MapsDirectory, "*.png")
            .Select(Path.GetFileNameWithoutExtension)
            .OfType<string>()
            .Where(name => !PortAuthoredMaps.Contains(name))
            .Order(StringComparer.Ordinal)
            .ToArray();

    public static string MapPath(string map) => Path.Combine(MapsDirectory, map + ".png");

    /// <summary>
    /// The bytes of a built-in map's PNG, with a failure message that says what
    /// to do rather than just that a file is missing.
    /// </summary>
    public static byte[] ReadMap(string map)
    {
        // Deliberately NOT RequireAvailable(): the maps are checked in, so a
        // map test no longer needs a reference checkout. RequireAvailable still
        // guards the tests that read Constants.xml or the scripts, which really
        // do need one.
        var path = MapPath(map);

        Assert.True(
            File.Exists(path),
            $"no map at {path}. The built-in maps are checked in at maps/; "
            + $"set {EnvironmentVariable} to read them from a checkout instead.");

        return File.ReadAllBytes(path);
    }

    public static void RequireAvailable() =>
        Assert.True(
            IsAvailable,
            $"""
             No reference checkout at {IncludedFiles}.

             These tests read the Gang Garrison 2 source, which is the specification this
             port is checked against. Unset {EnvironmentVariable} to have it cloned into
             {CacheRoot}, or point it at a checkout of {Upstream}.
             """);
}
