using Gg2.Bots;

namespace Gg2.Tests;

/// <summary>
/// Locates the reference checkout — the Game Maker 8 implementation that is also
/// the client, and therefore the specification.
/// </summary>
/// <remarks>
/// The map tests read the maps out of it rather than copying them here. That is
/// deliberate: a copied map is a map that can silently go stale, and phase 0's
/// exit criterion is about the maps the stock client actually ships.
/// <para>
/// Set <c>GG2_REFERENCE</c> to override the path. The tree is <b>read-only</b>
/// from this repo (CLAUDE.md).
/// </para>
/// <para>
/// ⚠️ <b>The default is stock upstream GG2, not the bot fork.</b> It used to be
/// <c>D:\code\Gang-Garrison-2</c>, a fork carrying 42 commits of its own bot and
/// nav work — 69 extra scripts and 198 extra constants. Tests grew to assert
/// against those, so "the specification" quietly meant one person's branch. This
/// port's bot layer has since diverged from that branch anyway, which leaves no
/// reason to check anything against it. Stock GG2 is the thing a stock client
/// runs, and that is the only thing this port owes compatibility to.
/// </para>
/// </remarks>
public static class ReferenceTree
{
    public const string EnvironmentVariable = "GG2_REFERENCE";

    /// <summary>
    /// Map names (without extension) that this repository authors itself —
    /// generated by a checked-in script, present in <c>maps/</c>, and absent
    /// from the reference by design.
    /// </summary>
    /// <remarks>
    /// ⚠️ Every census that makes a claim about what the SHIPPED maps contain
    /// must exclude these, or adding a port-authored map silently changes what
    /// "no shipped map does X" means. <see cref="MapCopyTests"/> asserts the
    /// other direction: none of these may exist in the reference tree.
    /// <c>gg_debug2</c> is <c>tools/gen-gg-debug2.js</c>'s output.
    /// </remarks>
    public static readonly IReadOnlySet<string> PortAuthoredMaps =
        new HashSet<string>(StringComparer.Ordinal) { "gg_debug2" };

    public const string NavCacheEnvironmentVariable = "GG2_NAVCACHE";

    private const string DefaultPath = @"D:\code\Gang-Garrison-2-upstream";

    /// <summary>Root of the checkout, whether or not it exists.</summary>
    public static string Root =>
        Environment.GetEnvironmentVariable(EnvironmentVariable) is { Length: > 0 } fromEnv
            ? fromEnv
            : DefaultPath;

    /// <summary>Where the built-in map PNGs live.</summary>
    public static string IncludedFiles => Path.Combine(Root, "Source", "gg2", "Included Files");

    /// <summary>
    /// Where the bot nav caches live: <c>GG2_NAVCACHE</c>, or <c>nav/</c> at the
    /// root of this repo.
    /// </summary>
    /// <remarks>
    /// ⚠️ <b>Deliberately NOT under <see cref="Root"/>.</b> These used to be read
    /// from the reference's <c>Source/build/botnav</c> — the GM8 build directory
    /// of whichever checkout <c>GG2_REFERENCE</c> pointed at — which quietly made
    /// 190-odd bot tests depend on a fork that had run the in-game generator.
    /// A nav graph is <em>this project's</em> artefact and the reference knows
    /// nothing about it, so it does not belong in a tree CLAUDE.md calls
    /// read-only.
    /// <para>
    /// ⚠️ <b>They are CHECKED IN as of 2026-09-01</b>, so a fresh clone has them
    /// and can run a bot. They were gitignored until then, which meant
    /// regenerating them needed a Game Maker 8 build of a fork.
    /// <see cref="RequireNavCache"/> still guards, because a clone can still
    /// delete them.
    /// <para>
    /// ✅ <b>Stored gzipped since 2026-09-03</b> — 1.11 MB rather than 35.68 MB
    /// on disk, and the same ~1.1 MB in the pack either way, since that is what
    /// git was storing before. <see cref="NavCache.List"/> accepts both
    /// containers, which is why this probe goes through it rather than globbing.
    /// </para>
    /// </para>
    /// </remarks>
    public static string NavCacheDirectory =>
        Environment.GetEnvironmentVariable(NavCacheEnvironmentVariable) is { Length: > 0 } fromEnv
            ? fromEnv
            : Path.Combine(RepositoryRoot, "nav");

    public static bool IsAvailable => Directory.Exists(IncludedFiles);

    public static bool HasNavCache =>
        Directory.Exists(NavCacheDirectory) && NavCache.List(NavCacheDirectory).Count > 0;

    public static void RequireNavCache() =>
        Assert.True(
            HasNavCache,
            $"""
             No bot nav caches at {NavCacheDirectory}.

             These are checked in, so a clone should have them — a missing nav/ means
             they were deleted, or {NavCacheEnvironmentVariable} points somewhere else.
             Otherwise run gg2-nav-gen over the built-in maps and either copy its
             output to that directory or point {NavCacheEnvironmentVariable} at it.
             """);

    /// <summary>
    /// This repo's root, found by walking up from the test binary until
    /// <c>Gg2.sln</c> turns up.
    /// </summary>
    /// <remarks>
    /// The alternative — copying the caches into the build output the way
    /// <c>Fixtures/</c> is copied — would put 34 MB through every build, twice
    /// over for Debug and Release.
    /// </remarks>
    private static string RepositoryRoot
    {
        get
        {
            for (var directory = new DirectoryInfo(AppContext.BaseDirectory);
                 directory is not null;
                 directory = directory.Parent)
            {
                if (File.Exists(Path.Combine(directory.FullName, "Gg2.sln")))
                    return directory.FullName;
            }

            // Only reachable if the tests are run from outside the tree; the
            // env var is then the way in, and RequireNavCache says so.
            return AppContext.BaseDirectory;
        }
    }

    /// <summary>
    /// Where the built-in map PNGs are read from: <c>maps/</c> at the root of
    /// this repo, or the reference's <c>Included Files</c> if that is missing.
    /// </summary>
    /// <remarks>
    /// ⚠️ <b>The maps are checked in as of 2026-09-01</b>, which reverses this
    /// type's original "the map tests read the maps out of it rather than
    /// copying them here". That decision had a real reason — <em>a copied map is
    /// a map that can silently go stale</em> — and copying them does not answer
    /// it by itself. <see cref="MapCopyTests"/> is the answer: whenever a
    /// reference checkout is present, every copied map is asserted
    /// byte-identical to the reference's. So the copy is gated rather than
    /// trusted, and the tests stop needing a checkout to run at all.
    /// <para>
    /// ⚠️ <b>Falling back to the reference matters for more than tidiness.</b>
    /// <c>LevelEntityTests</c> compares every entity against
    /// <c>Fixtures/maps.json</c>; pointing it at a copy that is never checked
    /// against the reference would leave both sides reading the same bytes and
    /// gate nothing about drift, which is the coverage that check preserves.
    /// </para>
    /// </remarks>
    public static string MapsDirectory
    {
        get
        {
            var copied = Path.Combine(RepositoryRoot, "maps");
            return File.Exists(Path.Combine(copied, "ctf_truefort.png")) ? copied : IncludedFiles;
        }
    }

    public static string MapPath(string map) => Path.Combine(MapsDirectory, map + ".png");

    /// <summary>
    /// The bytes of a built-in map's PNG, with a failure message that says what
    /// to do rather than just that a file is missing.
    /// </summary>
    public static byte[] ReadMap(string map)
    {
        // ⚠️ Deliberately NOT RequireAvailable(): the maps are checked in, so a
        // map test no longer needs a reference checkout. RequireAvailable still
        // guards the tests that read Constants.xml or the scripts, which really
        // do need one.
        var path = MapPath(map);

        Assert.True(
            File.Exists(path),
            $"no map at {path}. The built-in maps are checked in at maps/; "
            + $"set {EnvironmentVariable} to read them from a checkout instead.");

        return File.ReadAllBytes(path);
    }

    public static void RequireAvailable() =>
        Assert.True(
            IsAvailable,
            $"""
             No reference checkout at {IncludedFiles}.

             These tests read the built-in maps out of the Gang Garrison 2 tree, which
             is the specification this port is checked against. Point {EnvironmentVariable}
             at a checkout to run them.
             """);
}
